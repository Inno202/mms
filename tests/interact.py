        await pg.goto(BASE+"learnerships.html", wait_until="networkidle")
        cta=await pg.get_attribute(".header-cta","href"); cur=await pg.get_attribute(".header-cta","aria-current")
        ok("header button goes to Learnerships", cta=="learnerships.html" and cur=="page", f"{cta} {cur}")
        await pg.click("#interest-form button[type=submit]"); await pg.wait_for_timeout(300)
