        a3=await pg.evaluate("[...document.querySelectorAll('.slide')].findIndex(s=>s.classList.contains('is-active'))")
        ok("paused slideshow stays put", a3==2, str(a3))
        await pg.click(".pause-btn"); await pg.wait_for_timeout(6900)
        a4=await pg.evaluate("[...document.querySelectorAll('.slide')].findIndex(s=>s.classList.contains('is-active'))")
        ok("playing slideshow advances", a4==3, str(a4))
        await pg.screenshot(path="/home/claude/test/shots/hero-desktop.png")
        # photo viewer
        await pg.goto(BASE+"impact.html", wait_until="networkidle")
        await pg.click(".zoomable >> nth=1"); await pg.wait_for_timeout(500)
        op=await pg.evaluate("document.getElementById('photo-viewer').open")
        cnt=await pg.text_content(".viewer-count")
        await pg.keyboard.press("ArrowRight"); await pg.wait_for_timeout(400)
        cnt2=await pg.text_content(".viewer-count")
        await pg.screenshot(path="/home/claude/test/shots/viewer.png")
        await pg.keyboard.press("Escape"); await pg.wait_for_timeout(300)
        cl=await pg.evaluate("!document.getElementById('photo-viewer').open")
