        # tampered select value
        await pg.evaluate("const o=document.createElement('option');o.value='<script>';o.textContent='x';document.getElementById('topic').append(o);document.getElementById('topic').value='<script>'")
        await pg.fill("#email","thandi@example.co.za"); await pg.fill("#phone","+27 82 555 0101"); await pg.fill("#message","We would like a learnership for 40 staff.")
        await pg.click("button[type=submit]"); await pg.wait_for_timeout(300)
