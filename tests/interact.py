        await pg.goto(BASE+"contact.html", wait_until="networkidle")
        await pg.click("button[type=submit]"); await pg.wait_for_timeout(400)
        inv=await pg.evaluate("[...document.querySelectorAll('[aria-invalid=true]')].map(e=>e.id)")
        foc=await pg.evaluate("document.activeElement.id")
        ok("empty submit flags required fields and focuses first", set(inv)=={"name","email","topic","message"} and foc=="name", f"{inv} focus={foc}")
        await pg.screenshot(path="/home/claude/test/shots/form-errors.png", full_page=False)
        await pg.fill("#name","Thandi Mokoena"); await pg.fill("#email","not-an-email"); await pg.fill("#phone","abc")
